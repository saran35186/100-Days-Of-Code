 #include <stdio.h>
 int main()
 {
    int A=3;
    int B=8;
    int sum;
    int difference;
    int product;
    int quotient;
    sum = A + B;
    difference = A - B;
    product = A * B;
    quotient = A / B;
    printf("the sum of two numbers is %d\n", sum);
    printf("the difference of two numbers is %d\n", difference);
    printf("the product of two numbers is%d\n", product);
    printf("the quotient of two numbers is %d\n",quotient);
    return 0;
 }
